package com.randonaughtica.interplanetary.client.render;

import com.randonaughtica.interplanetary.InterplanetaryStuff;
import com.randonaughtica.interplanetary.entity.RocketEntity;
import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
import net.minecraft.client.model.ModelData;
import net.minecraft.client.model.ModelPart;
import net.minecraft.client.model.ModelPartBuilder;
import net.minecraft.client.model.ModelPartData;
import net.minecraft.client.model.ModelTransform;
import net.minecraft.client.model.TexturedModelData;
import net.minecraft.client.render.RenderLayer;
import net.minecraft.client.render.entity.model.EntityModelLayer;
import net.minecraft.client.render.entity.model.SinglePartEntityModel;

/**
 * Rocket model, 4.6 blocks tall. Y grows downwards in model space; the renderer flips it.
 * The UV layout must match the rocket textures generated by tools/generate.py.
 */
@Environment(EnvType.CLIENT)
public class RocketEntityModel extends SinglePartEntityModel<RocketEntity> {
    public static final EntityModelLayer LAYER = new EntityModelLayer(InterplanetaryStuff.id("rocket"), "main");

    private final ModelPart root;

    public RocketEntityModel(ModelPart root) {
        super(RenderLayer::getEntityCutout);
        this.root = root;
    }

    public static TexturedModelData getTexturedModelData() {
        ModelData data = new ModelData();
        ModelPartData root = data.getRoot();
        root.addChild("body", ModelPartBuilder.create().uv(0, 0).cuboid(-8, -40, -8, 16, 34, 16), ModelTransform.NONE);
        root.addChild("upper", ModelPartBuilder.create().uv(64, 0).cuboid(-6, -56, -6, 12, 16, 12), ModelTransform.NONE);
        root.addChild("nozzle", ModelPartBuilder.create().uv(64, 28).cuboid(-5, -6, -5, 10, 6, 10), ModelTransform.NONE);
        root.addChild("nose_lower", ModelPartBuilder.create().uv(0, 50).cuboid(-4, -64, -4, 8, 8, 8), ModelTransform.NONE);
        root.addChild("nose_upper", ModelPartBuilder.create().uv(32, 50).cuboid(-2, -70, -2, 4, 6, 4), ModelTransform.NONE);
        root.addChild("tip", ModelPartBuilder.create().uv(48, 50).cuboid(-1, -74, -1, 2, 4, 2), ModelTransform.NONE);
        root.addChild("fin_left", ModelPartBuilder.create().uv(0, 66).cuboid(-14, -22, -1, 6, 18, 2), ModelTransform.NONE);
        root.addChild("fin_right", ModelPartBuilder.create().uv(0, 66).cuboid(8, -22, -1, 6, 18, 2), ModelTransform.NONE);
        root.addChild("fin_front", ModelPartBuilder.create().uv(16, 66).cuboid(-1, -22, -14, 2, 18, 6), ModelTransform.NONE);
        root.addChild("fin_back", ModelPartBuilder.create().uv(16, 66).cuboid(-1, -22, 8, 2, 18, 6), ModelTransform.NONE);
        root.addChild("window", ModelPartBuilder.create().uv(32, 66).cuboid(-3, -36, -9, 6, 6, 1), ModelTransform.NONE);
        return TexturedModelData.of(data, 128, 128);
    }

    @Override
    public ModelPart getPart() {
        return root;
    }

    @Override
    public void setAngles(RocketEntity entity, float limbAngle, float limbDistance, float animationProgress,
                          float headYaw, float headPitch) {
    }
}
